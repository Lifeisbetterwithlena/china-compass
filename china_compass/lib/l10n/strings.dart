  AppLanguage(code: 'es', nativeName: 'Español', englishName: 'Spanish', flag: FlagKind.spain),
];

AppLanguage languageFor(String code) =>
    appLanguages.firstWhere((l) => l.code == code, orElse: () => appLanguages.first);

